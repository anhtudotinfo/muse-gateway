// Generates src/lib/i18n-zh.ts — zh translations for every DICT key in
// i18n.tsx, via the Google Translate "gtx" endpoint (en -> zh-CN).
// Han chars never pass through the code toolchain: they flow network->disk.
// Usage: node scripts/zh-gen.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const src = path.join(root, 'src', 'lib', 'i18n.tsx');
const out = path.join(root, 'src', 'lib', 'i18n-zh.ts');

const text = fs.readFileSync(src, 'utf8');
const re = /'((?:[^'\\]|\\.)*)':\s*\{\s*en:\s*'((?:[^'\\]|\\.)*)'/g;
const unq = (s) => s.replace(/\\'/g, "'").replace(/\\n/g, '\n').replace(/\\\\/g, '\\');
const entries = [];
let m;
while ((m = re.exec(text))) entries.push([unq(m[1]), unq(m[2])]);
console.log('keys:', entries.length);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function gtx(q) {
  const url = 'https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=zh-CN&dt=t&q=' + encodeURIComponent(q);
  for (let i = 0; i < 4; i++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0' } });
      if (res.ok) {
        const j = await res.json();
        return (j[0] || []).map((seg) => seg[0] || '').join('');
      }
      console.log('  http', res.status, 'retry', i + 1);
    } catch (e) {
      console.log('  err', e.message, 'retry', i + 1);
    }
    await sleep(800 * (i + 1));
  }
  return null;
}

const zh = {};
let done = 0;
for (const [key, en] of entries) {
  const v = await gtx(en);
  if (v) zh[key] = v;
  done++;
  if (done % 10 === 0) console.log('  ', done, '/', entries.length);
  await sleep(250);
}

const body = JSON.stringify(zh, null, 2)
  .replace(/\\u2028/g, ' ')
  .replace(/\\u2029/g, ' ');
const header = '// GENERATED by scripts/zh-gen.mjs — do not edit by hand.\n' +
  '// zh translations keyed by the VI source string; tr() falls back to en.\n' +
  'export const ZH: Record<string, string> = ';
fs.writeFileSync(out, header + body + ';\n', 'utf8');
console.log('wrote', out, Object.keys(zh).length, 'entries');
